## Pandas 데이터접근
# 설명: Pandas에서 데이터에 접근하는 방법을 소개합니다.
# DataFrame에서 특정 열, 행, 또는 셀에 접근하는 방법을 배웁니다.

import pandas as pd

df = pd.DataFrame({
    "이름": ["영완", "지수", "민준", "수연", "태양"],
    "나이": [32, 28, 35, 24, 30],
    "점수": [85, 92, 78, 96, 88],
    "도시": ["서울", "부산", "서울", "대구", "서울"]
})

# 열 접근
print("-- 점수 열 --")
print(df["점수"])

print("\n-- 이름 + 점수 --")
print(df[["이름", "점수"]])

# 행 접근
print("\n-- 첫번째 행 --")
print(df.iloc[0])  # 위치 기반 인덱싱

# 조건 필터링
print("\n-- 점수 90 이상 --")
print(df[df["점수"] >= 90])

print("\n-- 서울 사람만 --")
print(df[df["도시"] == "서울"])

# 복합 조건 (and: &, or: |)
print("\n-- 서울 + 85점 이상 --")
print(df[(df["도시"] == "서울") & (df["점수"] >=85)])